def groups_of(name):
    """메뉴 이름 → 식품군 id 목록. 과일은 이름 끝이 맞을 때만('사과주스'는 맞고 '배추'는 아니다)."""
    out = []
    if any(name == f or (len(f) > 1 and len(name) <= len(f) + 2 and name.endswith(f)) for f in FRUITS):
        out.append("fruit")
    out += [gid for gid, rule in RULES if rule.search(name) and gid not in out]
    return out


def screens(saved):
    """저장값 [{"key", "on"}] → 화면 정보 + on, 저장 순서대로. 저장에 없는 화면은 켠 채 뒤에 붙고, 식판 사진은 저장값과 상관없이 켜진다."""
    by_key = {s["key"]: s for s in SCREENS}
    out = {}
    for item in saved:
        if item.get("key") in by_key:
            out.setdefault(item["key"], bool(item.get("on", True)))
    for key in SCREEN_KEYS:
        out.setdefault(key, True)
    return [{**by_key[k], "on": on or k == PHOTO, "lock": k == PHOTO} for k, on in out.items()]
